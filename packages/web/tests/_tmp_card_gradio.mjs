import { chromium } from 'playwright-core';
import { chromiumLaunchOptions } from '../../../scripts/browser.mjs';
const url = process.env.URL; const out = process.env.OUT;
const browser = await chromium.launch(chromiumLaunchOptions());
const page = await browser.newPage({ viewport: { width: 1500, height: 950 }, colorScheme: 'dark' });
const logs = []; page.on('console', (m) => { if (['error','warning'].includes(m.type())) logs.push(m.type()+': '+m.text()); }); page.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
await page.goto(url);
const frame = page.frameLocator('iframe[title="AtomWorks Studio"]');
await frame.locator('#rfd4p-task-grid .rfd4p-task-card').first().waitFor({ timeout: 60000 });
console.log('cards', await frame.locator('.rfd4p-task-card').count());
console.log('badge', await frame.locator('#webgpu-badge').textContent().catch(() => 'none'), '|', await frame.locator('.card-title-row').first().innerText());
await page.screenshot({ path: out + '/space-start.png' });
await frame.locator('.rfd4p-task-card', { hasText: 'Protein from scratch' }).click();
await frame.locator('#predict').waitFor();
await frame.locator('#predict:not([disabled])').waitFor({ timeout: 60000 });
console.log('early stop visible', await frame.locator('#early-stop').isVisible().catch(() => false));
await page.screenshot({ path: out + '/space-job.png' });
await frame.locator('#predict').click();
try { await frame.locator('#design-results:not([hidden])').waitFor({ timeout: 30000 }); } catch (e) { console.log('NO RESULT; status:', await frame.locator('#rfd4p-status-message').textContent()); console.log(logs.join('\n')); await page.screenshot({ path: out + '/space-fail.png' }); await browser.close(); process.exit(1); }
await page.waitForTimeout(1500);
console.log('rows', await frame.locator('#design-results table tbody tr').count());
console.log('status', await frame.locator('#rfd4p-status-message').textContent());
await page.screenshot({ path: out + '/space-result.png' });
console.log(logs.slice(0, 8).join('\n'));
await browser.close();
